import docx
from docx.oxml.ns import qn
from docx.oxml import OxmlElement

def insert_toc(paragraph):
    # clear existing text just in case
    paragraph.text = ""
    run = paragraph.add_run()
    fldChar1 = OxmlElement('w:fldChar')
    fldChar1.set(qn('w:fldCharType'), 'begin')
    run._r.append(fldChar1)
    
    instrText = OxmlElement('w:instrText')
    instrText.set(qn('xml:space'), 'preserve')
    instrText.text = 'TOC \\o "1-3" \\h \\z \\u'
    run._r.append(instrText)
    
    fldChar2 = OxmlElement('w:fldChar')
    fldChar2.set(qn('w:fldCharType'), 'separate')
    run._r.append(fldChar2)
    
    # Add a dummy update text so user sees something to update
    run.add_text("Klik kanan di sini dan pilih 'Update Field' untuk menampilkan Daftar Isi otomatis")
    
    fldChar3 = OxmlElement('w:fldChar')
    fldChar3.set(qn('w:fldCharType'), 'end')
    run._r.append(fldChar3)

def update_front_matter():
    path = "PENGERJAAN TESIS BAB I - BAB V/front_matter/FRONT_MATTER_DRAFT.docx"
    doc = docx.Document(path)
    
    abstrak_id = "Penelitian ini mengembangkan strategi segmentasi probabilistik untuk mengoptimalkan rekrutmen calon mahasiswa baru di ITSNU Pekalongan. Kompleksitas data pendaftaran dengan dimensi tinggi, seperti variasi teks dari kolom nama, asal sekolah, dan alamat, menjadi tantangan dalam pengelompokan menggunakan metode konvensional. Pendekatan hybrid diusulkan dengan mengintegrasikan model bahasa IndoBERT untuk ekstraksi fitur semantik berdimensi 768, Gaussian Mixture Model (GMM) untuk clustering probabilistik, dan Large Language Model (LLM) untuk generasi persona secara otomatis. Metodologi CRISP-DM diterapkan pada data pendaftaran periode 2019-2024. Evaluasi optimalisasi jumlah cluster (k) menggunakan skor Bayesian Information Criterion (BIC), Silhouette Coefficient, dan Adjusted Rand Index (ARI) menunjukkan bahwa model stabil pada k=5. Hasil segmentasi mengidentifikasi lima persona utama: Kelompok Dominan Regional, Kelompok Potensial Akademik, Kelompok Spesifik Geografis, Kelompok Diversifikasi Jalur, dan Kelompok Anomali Jarak. Analisis pergerakan cluster antar tahun yang dihasilkan oleh LLM mengkonfirmasi dinamika pergeseran minat yang stabil namun memiliki tren adaptif. Integrasi IndoBERT, GMM, dan LLM terbukti mampu mengatasi permasalahan high-dimensionality serta memberikan deskripsi klaster yang lebih kaya dan relevan secara bisnis, mendukung pengambilan keputusan rekrutmen yang lebih terarah dan efisien."
    abstrak_en = "This research develops a probabilistic segmentation strategy to optimize the recruitment of prospective new students at ITSNU Pekalongan. The complexity of high-dimensional enrollment data, such as text variations in name, school origin, and address columns, poses challenges for clustering using conventional methods. A hybrid approach is proposed by integrating the IndoBERT language model for 768-dimensional semantic feature extraction, Gaussian Mixture Model (GMM) for probabilistic clustering, and Large Language Model (LLM) for automated persona generation. The CRISP-DM methodology is applied to registration data from 2019-2024. Evaluation of cluster quantity optimization (k) using Bayesian Information Criterion (BIC), Silhouette Coefficient, and Adjusted Rand Index (ARI) scores indicates model stability at k=5. The segmentation results identify five main personas: Regional Dominant Group, Academic Potential Group, Geographic Specific Group, Pathway Diversification Group, and Distance Anomaly Group. Causal analysis of cluster movements across years generated by the LLM confirms the dynamics of interest shifts that are stable yet adaptive in trend. The integration of IndoBERT, GMM, and LLM is proven capable of overcoming high-dimensionality issues while providing richer, business-relevant cluster descriptions, thereby supporting more targeted and efficient recruitment decision-making."

    found_toc = False
    for p in doc.paragraphs:
        if "DAFTAR ISI" in p.text and len(p.text) < 15:
            # The next paragraph is usually empty or for TOC
            found_toc = True
            # Let's just insert toc right into the next paragraph if possible, or create one
            continue
            
        if found_toc:
            # We are right after DAFTAR ISI
            insert_toc(p)
            found_toc = False
            
        if "[Isi Abstrak Bahasa Indonesia" in p.text:
            p.text = abstrak_id
        elif "[Isi Abstract Bahasa Inggris" in p.text:
            p.text = abstrak_en
            
    doc.save(path)
    print("Updated FRONT_MATTER_DRAFT.docx with abstracts and TOC field")

if __name__ == "__main__":
    update_front_matter()
